import { test } from 'node:test';
import * as assert from 'node:assert/strict';
import { catalogTemplateFiles } from '../src/core/catalogAuthoring';
import { checkVersionBumps, RepoSnapshot, validateCatalog } from '../src/core/catalogValidate';

function snap(files: Record<string, string>): RepoSnapshot {
    return { files: Object.keys(files), read: p => files[p] };
}

const agent = (desc: string) => `---\ndescription: ${desc}\n---\nBody\n`;
const skill = (name: string) => `---\nname: ${name}\ndescription: Does things. Use when: testing.\n---\nBody\n`;
const cfg = (template: Record<string, unknown>) => JSON.stringify({ template });

const base: Record<string, string> = {
    'template.config.json': cfg({ id: 'bc-alm', name: 'BC ALM', version: '1.0.0' }),
    '.github/agents/bc-dev.agent.md': agent('Dev. Use when: coding.'),
    '.github/agents/bc-deploy.agent.md': agent('Deploy. Use when: releasing.'),
    '.github/skills/bc-ship-release/SKILL.md': skill('bc-ship-release')
};

const errors = (files: Record<string, string>) => validateCatalog(snap(files)).filter(i => i.severity === 'error');

test('validateCatalog accepts a valid catalog with a variant', () => {
    const files = {
        ...base,
        '.templates/README.md': '# Catalog\n',
        '.templates/bc-alm-lite/template.config.json': cfg({ id: 'bc-alm-lite', name: 'Lite', version: '0.1.0', extends: 'bc-alm', remove: ['agent:bc-deploy', 'skill:bc-ship-release'] }),
        '.templates/bc-alm-lite/CHANGELOG.md': '# Changelog\n\n## [0.1.0] - 2026-01-01\n\n- Initial.\n',
        '.templates/bc-upgrade/template.config.json': cfg({ id: 'bc-upgrade', name: 'Upgrade', version: '0.1.0' }),
        '.templates/bc-upgrade/.github/agents/bc-upgrade.agent.md': agent('Upgrade. Use when: upgrading.')
    };
    assert.deepEqual(errors(files), []);
});

test('validateCatalog: catalog files generated by the extension are valid', () => {
    const files: Record<string, string> = { ...base };
    for (const f of catalogTemplateFiles({ id: 'bc-x', name: 'X', extends: 'bc-alm', remove: ['agent:bc-deploy'] }, [
        { srcRel: '.github/agents/bc-dev.agent.md', text: agent('Dev v2. Use when: coding.'), changes: [] }
    ])) { files[f.path] = f.text; }
    assert.deepEqual(errors(files), []);
});

test('validateCatalog flags manifest problems with readable messages', () => {
    const e = errors({
        ...base,
        '.templates/bc-upgrade/template.config.json': cfg({ id: 'bc-alm', name: 'Dup', version: '0.1.0' }),
        '.templates/Upper/template.config.json': cfg({ id: 'upper', name: 'U', version: '0.1.0' }),
        '.templates/nover/template.config.json': cfg({ id: 'nover', name: 'N' }),
        '.templates/badver/template.config.json': cfg({ id: 'badver', name: 'B', version: 'one' }),
        '.templates/noconfig/README.md': '# x\n',
        '.templates/badjson/template.config.json': '{ nope',
        '.templates/noblock/template.config.json': '{ "values": {} }'
    });
    const msg = (f: string) => e.filter(i => i.file.startsWith(`.templates/${f}`)).map(i => i.message).join(' | ');
    assert.match(msg('bc-upgrade'), /must equal the folder name "bc-upgrade"/);
    assert.match(msg('Upper'), /must equal the folder name/);
    assert.match(msg('nover'), /version is required/);
    assert.match(msg('badver'), /not a semantic version/);
    assert.match(msg('noconfig'), /has no template\.config\.json/);
    assert.match(msg('badjson'), /Not valid JSON/);
    assert.match(msg('noblock'), /Missing the "template" block/);
});

test('validateCatalog flags duplicate ids, missing extends targets, cycles and unknown removes', () => {
    const dupRoot = errors({ ...base, '.templates/bc-alm/template.config.json': cfg({ id: 'bc-alm', name: 'Again', version: '0.1.0' }) });
    assert.match(dupRoot.map(i => i.message).join(), /Duplicate template id "bc-alm"/);

    const e = errors({
        ...base,
        '.templates/a/template.config.json': cfg({ id: 'a', name: 'A', version: '0.1.0', extends: 'b' }),
        '.templates/b/template.config.json': cfg({ id: 'b', name: 'B', version: '0.1.0', extends: 'a' }),
        '.templates/c/template.config.json': cfg({ id: 'c', name: 'C', version: '0.1.0', extends: 'missing' }),
        '.templates/d/template.config.json': cfg({ id: 'd', name: 'D', version: '0.1.0', extends: 'bc-alm', remove: ['agent:bc-dev', 'agent:nope'] })
    }).map(i => `${i.file}: ${i.message}`);
    assert.ok(e.some(m => m.startsWith('.templates/a/') && /cycle: a -> b -> a/.test(m)), e.join('\n'));
    assert.ok(e.some(m => m.startsWith('.templates/c/') && /"missing" is not a template/.test(m)));
    assert.ok(e.some(m => m.startsWith('.templates/d/') && /remove "agent:nope"/.test(m)));
    assert.ok(!e.some(m => /agent:bc-dev/.test(m)));
});

test('validateCatalog: a remove of a component removed earlier in the chain is reported', () => {
    const e = errors({
        ...base,
        '.templates/lite/template.config.json': cfg({ id: 'lite', name: 'L', version: '0.1.0', extends: 'bc-alm', remove: ['agent:bc-deploy'] }),
        '.templates/tiny/template.config.json': cfg({ id: 'tiny', name: 'T', version: '0.1.0', extends: 'lite', remove: ['agent:bc-deploy'] })
    });
    assert.equal(e.length, 1);
    assert.match(e[0].message, /"agent:bc-deploy" is not a component of "lite"/);
});

test('validateCatalog runs the customization validator on template files', () => {
    const e = errors({
        ...base,
        '.templates/bc-upgrade/template.config.json': cfg({ id: 'bc-upgrade', name: 'U', version: '0.1.0' }),
        '.templates/bc-upgrade/.github/agents/bc-upgrade.agent.md': '---\nname: x\n---\nNo description\n',
        '.templates/bc-upgrade/.github/skills/Bad_Name/SKILL.md': '---\nname: Bad_Name\ndescription: x\n---\n'
    });
    assert.ok(e.some(i => i.file === '.templates/bc-upgrade/.github/agents/bc-upgrade.agent.md' && /agent-description/.test(i.message)));
    assert.ok(e.some(i => i.file === '.templates/bc-upgrade/.github/skills/Bad_Name/SKILL.md' && /skill-name-format/.test(i.message)));
});

test('validateCatalog: handoff targets resolve against the variant\'s effective agents', () => {
    const handoff = (to: string) => `---\ndescription: X. Use when: y.\nhandoffs:\n  - label: Go\n    agent: ${to}\n---\nBody\n`;
    const warnings = (to: string) => validateCatalog(snap({
        ...base,
        '.templates/lite/template.config.json': cfg({ id: 'lite', name: 'L', version: '0.1.0', extends: 'bc-alm', remove: ['agent:bc-deploy'] }),
        '.templates/lite/.github/agents/bc-pr.agent.md': handoff(to)
    })).filter(i => /agent-handoff-target/.test(i.message));
    assert.equal(warnings('bc-dev').length, 0);
    assert.equal(warnings('bc-deploy').length, 1);
});

test('checkVersionBumps requires a version bump and changelog section for changed catalog templates', () => {
    const before = {
        ...base,
        '.templates/lite/template.config.json': cfg({ id: 'lite', name: 'L', version: '0.1.0', extends: 'bc-alm' }),
        '.templates/lite/CHANGELOG.md': '# Changelog\n\n## [0.1.0] - 2026-01-01\n\n- Initial.\n',
        '.templates/lite/README.md': '# Lite\n',
        '.templates/lite/.github/agents/x.agent.md': agent('X. Use when: y.')
    };
    const changedAgent = { ...before, '.templates/lite/.github/agents/x.agent.md': agent('X2. Use when: y.') };

    const noBump = checkVersionBumps(['.templates/lite/.github/agents/x.agent.md'], snap(before), snap(changedAgent));
    assert.equal(noBump.length, 1);
    assert.match(noBump[0].message, /still 0\.1\.0/);

    const bumpedNoLog = { ...changedAgent, '.templates/lite/template.config.json': cfg({ id: 'lite', name: 'L', version: '0.1.1', extends: 'bc-alm' }) };
    const r2 = checkVersionBumps(['.templates/lite/.github/agents/x.agent.md', '.templates/lite/template.config.json'], snap(before), snap(bumpedNoLog));
    assert.equal(r2.length, 1);
    assert.match(r2[0].message, /## \[0\.1\.1\]/);

    const ok = { ...bumpedNoLog, '.templates/lite/CHANGELOG.md': '# Changelog\n\n## [0.1.1] - 2026-02-01\n\n- Tweak.\n\n## [0.1.0] - 2026-01-01\n\n- Initial.\n' };
    assert.deepEqual(checkVersionBumps(['.templates/lite/.github/agents/x.agent.md', '.templates/lite/template.config.json', '.templates/lite/CHANGELOG.md'], snap(before), snap(ok)), []);

    assert.deepEqual(checkVersionBumps(['.templates/lite/README.md'], snap(before), snap({ ...before, '.templates/lite/README.md': '# Lite!\n' })), []);
    assert.deepEqual(checkVersionBumps(['.github/agents/bc-dev.agent.md'], snap(base), snap(base)), []);

    const added = { ...base, '.templates/new/template.config.json': cfg({ id: 'new', name: 'N', version: '0.1.0' }) };
    const r3 = checkVersionBumps(['.templates/new/template.config.json'], snap(base), snap(added));
    assert.equal(r3.length, 1);
    assert.match(r3[0].file, /new\/CHANGELOG\.md$/);
});
